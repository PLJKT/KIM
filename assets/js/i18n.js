var CURRENT_LANG = (localStorage.getItem('kim_lang') || 'en');

function t(key) {
  var d = I18N[CURRENT_LANG] || I18N.en;
  if (d[key] !== undefined) return d[key];
  if (I18N.en[key] !== undefined) return I18N.en[key];
  return key;
}

function applyI18n() {
  document.documentElement.lang = CURRENT_LANG;
  var nodes = document.querySelectorAll('[data-i18n]');
  for (var i = 0; i < nodes.length; i++) {
    nodes[i].textContent = t(nodes[i].getAttribute('data-i18n'));
  }
  var inputs = document.querySelectorAll('[data-i18n-ph]');
  for (var j = 0; j < inputs.length; j++) {
    inputs[j].setAttribute('placeholder', t(inputs[j].getAttribute('data-i18n-ph')));
  }
}

function setLang(lang) {
  CURRENT_LANG = lang;
  localStorage.setItem('kim_lang', lang);
  applyI18n();
  if (window.renderAll) { try { window.renderAll(); } catch (e) { console && console.error(e); } }
}
